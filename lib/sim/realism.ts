/**
 * Power, Thermal & Soil Dynamics Realism Engine (Pack F — F-006)
 *
 * Implements physically based battery consumption, solar radiative replenishment,
 * motor thermal rise/cooling with smooth derating, and soil traction properties.
 */

export interface PowerThermalState {
  batteryWh: number;
  batteryCapacityWh: number;
  batteryChargePct: number; // 0.0 .. 1.0
  isShutdown: boolean;
  motorTempC: number;
  ambientTempC: number;
  thermalDerateFactor: number; // 0.2 .. 1.0 (1.0 = full power)
  solarYieldWatts: number;
}

export interface PowerThermalConfig {
  capacityWh: number;
  idlePowerWatts: number;
  solarMaxWatts: number;
  derateTempThresholdC: number;
  criticalTempC: number;
}

export const DEFAULT_POWER_CONFIG: PowerThermalConfig = {
  capacityWh: 120.0,
  idlePowerWatts: 14.0,
  solarMaxWatts: 45.0,
  derateTempThresholdC: 65.0,
  criticalTempC: 90.0,
};

export class PowerThermalSimulator {
  private batteryWh: number;
  private motorTempC = 25.0;
  private readonly config: PowerThermalConfig;

  constructor(config: Partial<PowerThermalConfig> = {}) {
    this.config = { ...DEFAULT_POWER_CONFIG, ...config };
    this.batteryWh = this.config.capacityWh;
  }

  public reset(): void {
    this.batteryWh = this.config.capacityWh;
    this.motorTempC = 25.0;
  }

  public step(
    dt: number,
    vx: number,
    vy: number,
    mass: number,
    isSunlit: boolean,
    sunAlignment: number
  ): PowerThermalState {
    const speed = Math.hypot(vx, vy);

    // 1. Mechanical & Idle Power Draw:
    // P_mech = P_idle + k1 * v^2 + k2 * mass * |v|
    const mechWatts = speed > 0.05 ? 18.0 + 35.0 * (speed * speed) + 0.8 * mass * speed : 0.0;
    const totalConsumptionWatts = this.config.idlePowerWatts + mechWatts;

    // 2. Solar Charging (when stationary or slow, facing sun)
    let solarWatts = 0;
    if (isSunlit && sunAlignment > 0) {
      solarWatts = this.config.solarMaxWatts * Math.max(0, sunAlignment);
    }

    const netWatts = totalConsumptionWatts - solarWatts;
    // Energy delta in Watt-hours
    const deltaWh = (netWatts * dt) / 3600.0;
    this.batteryWh = Math.max(0, Math.min(this.config.capacityWh, this.batteryWh - deltaWh));

    // 3. Thermal Dynamics:
    // Heat generated by electrical load; radiative cooling toward ambient space (-50C shadow, +40C sun)
    const ambientC = isSunlit ? 35.0 : -45.0;
    const heatGen = totalConsumptionWatts * 0.012;
    const heatDissipation = (this.motorTempC - ambientC) * 0.045;
    this.motorTempC += (heatGen - heatDissipation) * dt;

    // 4. Smooth Thermal Derating
    let derateFactor = 1.0;
    if (this.motorTempC > this.config.derateTempThresholdC) {
      const over = this.motorTempC - this.config.derateTempThresholdC;
      const span = this.config.criticalTempC - this.config.derateTempThresholdC;
      derateFactor = Math.max(0.2, 1.0 - (over / span) * 0.8);
    }

    const chargePct = this.batteryWh / this.config.capacityWh;
    const isShutdown = this.batteryWh <= 0.01;

    return {
      batteryWh: Number(this.batteryWh.toFixed(2)),
      batteryCapacityWh: this.config.capacityWh,
      batteryChargePct: Number(chargePct.toFixed(3)),
      isShutdown,
      motorTempC: Number(this.motorTempC.toFixed(1)),
      ambientTempC: ambientC,
      thermalDerateFactor: Number(derateFactor.toFixed(3)),
      solarYieldWatts: Number(solarWatts.toFixed(1)),
    };
  }
}
